def build(root):
    a = os.path.join(root, "assets", "starserver")
    for name, (pal, art) in ICONS.items():
        rows = [r.ljust(16, '.')[:16] for r in art.strip("\n").split("\n")][:16]
        rows += ['.' * 16] * (16 - len(rows))
        im = Img(16, 16)
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch != '.':
                    im.put(x, y, hx(pal[ch], 200 if ch == 's' else 255))
        im.save(os.path.join(a, "textures", "item", "drop", name + ".png"))
        for sub, data in (("models/item/drop", {"parent": "minecraft:item/generated", "textures": {"layer0": f"starserver:item/drop/{name}"}}),
                          ("items/drop", {"model": {"type": "minecraft:model", "model": f"starserver:item/drop/{name}"}})):
            d = os.path.join(a, *sub.split("/"))
            os.makedirs(d, exist_ok=True)
            json.dump(data, open(os.path.join(d, name + ".json"), "w"))
    print("드롭 아이콘", len(ICONS), "개 →", a)


if __name__ == "__main__":
    build(ROOT)
